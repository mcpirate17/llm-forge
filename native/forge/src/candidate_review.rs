#[derive(Args)]
pub struct ReviewArgs {
    #[command(flatten)]
    selection: SelectionArgs,
    /// Resolve all obligations without executing tools unless explicitly requested.
    #[arg(long)]
    execute: bool,
    /// Maximum seconds to wait for the host governance lock.
    #[arg(long, default_value_t = 30)]
    lock_timeout: u64,
    /// Operator session identity used for ownership observations.
    #[arg(long, default_value = "")]
    owner: String,
    #[command(flatten)]
    outputs: exports::Outputs,
    /// Optional operator-owned contract registry for candidates without a bundled registry.
    #[arg(long, requires = "registry_sha256")]
    registry: Option<PathBuf>,
    #[arg(long, requires = "registry")]
    registry_sha256: Option<String>,
    /// Installed runner file bundle generated by candidate runner-bundle.
    #[arg(long, requires = "mutation_runner_sha256")]
    mutation_runner_bundle: Option<PathBuf>,
    #[arg(long, requires = "mutation_runner_bundle")]
    mutation_runner_sha256: Option<String>,
    /// Exact operator-held guest extension and its SHA-256.
    #[arg(long, requires = "equivalence_guest_sha256")]
    equivalence_guest: Option<PathBuf>,
    #[arg(long, requires = "equivalence_guest")]
    equivalence_guest_sha256: Option<String>,
    /// Captured configured test-record SQLite store and its SHA-256.
    #[arg(long, requires = "equivalence_store_sha256")]
    equivalence_store: Option<PathBuf>,
    #[arg(long, requires = "equivalence_store")]
    equivalence_store_sha256: Option<String>,
    /// Exact operator-owned output directory named by captured run_artifacts.
    #[arg(long)]
    equivalence_artifacts: Option<PathBuf>,
}

fn required(plans: &[Arc<CheckPlan>]) -> Result<Vec<String>> {
    let mut seen = BTreeSet::from(["engine-integrity", "attestation"]);
    let mut ids = vec!["engine-integrity".to_owned()];
    for plan in plans {
        ensure!(
            seen.insert(&plan.id),
            "reserved or duplicate review check ID {}",
            plan.id
        );
        ids.push(plan.id.clone());
    }
    ids.push("attestation".into());
    Ok(ids)
}

pub fn run(args: ReviewArgs, stamp: &BuildStamp) -> Result<Value> {
    args.outputs.validate()?;
    ensure!(
        args.lock_timeout <= 3600,
        "review lock timeout exceeds 3600 seconds"
    );
    let lease = if args.execute {
        Some(crate::candidate_review_lock::ReviewLock::acquire(
            args.selection.repository(),
            std::time::Duration::from_secs(args.lock_timeout),
        )?)
    } else {
        None
    };
    let started = Instant::now();
    let wall = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .context("review clock before epoch")?
        .as_secs_f64();
    let interrupts = args.execute.then(Interrupts::install).transpose()?;
    let selection = Arc::new(Selection::load(&args.selection)?);
    selection
        .surface
        .context("review requires an explicit --surface")?;
    let budget = selection
        .grants
        .batch
        .context("review requires an operator batch budget")?;
    let workers = selection.policy.document["max_workers"]
        .as_u64()
        .context("policy max_workers missing")?;
    let parallelism = budget.parallelism(workers, selection.grants.resources)?;
    let plans = crate::candidate_batch::select(&selection, &[])?;
    let ids = required(&plans)?;
    if !args.execute {
        return Ok(
            json!({"schema_version":1,"selection":selection.output(),"executed":false,
            "review_complete":false,"execution_verified":false,"approval":false,
            "required_checks":ids,"checks":plans.iter().map(|p| json!({"id":p.id,
                "scheduled":p.scheduled,"files":p.files,"kind":p.normalized["kind"]})).collect::<Vec<_>>(),
            "admitted_parallelism":parallelism}),
        );
    }
    let mut observation = execute(
        &args,
        &selection,
        &plans,
        stamp,
        interrupts.as_ref().expect("executing"),
        parallelism,
    )?;
    if interrupts.as_ref().expect("executing").interrupted()? {
        observation.cancelled = true;
        observation
            .results
            .obligation("cancellation", "review interrupted");
    }
    lease.as_ref().expect("executing").verify()?;
    let report = receipt::build(&selection, &ids, observation, wall, started)?;
    lease.as_ref().expect("executing").verify()?;
    args.outputs.publish(&report)?;
    lease.as_ref().expect("executing").verify()?;
    Ok(report)
}

fn execute(
    args: &ReviewArgs,
    selection: &Arc<Selection>,
    plans: &[Arc<CheckPlan>],
    stamp: &BuildStamp,
    interrupts: &Interrupts,
    parallelism: usize,
) -> Result<collect::Observation> {
    let source = selection.source()?;
    let snapshot = Snapshot::create(
        &source,
        &selection.candidate.tree_oid,
        &selection
            .grants
            .scratch_parent
            .join(crate::resource_id("forge-review")?),
        Limits::default(),
    )?;
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .max_blocking_threads(parallelism + 2)
        .build()?;
    let collected = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
        collect::run(
            args,
            selection,
            &source,
            &snapshot,
            plans,
            stamp,
            &runtime,
            interrupts,
            parallelism,
        )
    }))
    .map_err(|_| anyhow::anyhow!("native review coordinator panicked"))
    .and_then(|r| r);
    // Never publish a successful receipt before the collector snapshot is gone.
    let cleanup = snapshot.discard();
    let mut observation = match collected {
        Ok(value) => value,
        Err(error) => {
            cleanup.with_context(|| format!("review snapshot cleanup failed after {error:#}"))?;
            return Err(error);
        }
    };
    if let Err(error) = cleanup {
        observation
            .results
            .obligation("snapshot-cleanup", format!("{error:#}"));
    }
    Ok(observation)
}

